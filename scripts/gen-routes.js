/**
 * Writes the route tables in api/_lib/routes/ from the handler files in
 * api/_routes/. Run `npm run routes` after adding, moving or deleting a
 * handler; the build runs this with --check and fails if a table is stale.
 *
 * Why: Vercel turns every file in api/ into its own function, and at 128 the
 * production build ran out of memory (2026-11-05). Handlers now live in
 * api/_routes/ (the underscore keeps Vercel from making functions of them)
 * and a handful of group functions (api/app.js, api/cron.js, ...) route to
 * them. A handler at api/_routes/orders/update.js answers /api/orders/update,
 * exactly as before; index.js answers its folder (/api/orders).
 *
 * The tables are plain `import('../../_routes/x.js')` lines, not a computed
 * path, because Vercel bundles a function by following its literal imports.
 */
import fs from 'fs'
import path from 'path'

const root = new URL('..', import.meta.url).pathname
const ROUTES = path.join(root, 'api/_routes')
const OUT = path.join(root, 'api/_lib/routes')

// First path segment -> group function (api/<group>.js). Anything not listed
// goes to `app`. A group is a separate Vercel function with its own limits.
export const GROUP_OF = {
  cron: 'cron',
  public: 'public',
  mcp: 'mcp',
  support: 'support',
  sales: 'sales',
  admin: 'admin',
  auth: 'admin',
  finance: 'admin',
}
export const GROUPS = ['app', ...new Set(Object.values(GROUP_OF))]

function walk(dir, out = []) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, e.name)
    if (e.isDirectory()) walk(full, out)
    else if (e.name.endsWith('.js') && !e.name.endsWith('.test.js')) out.push(full)
  }
  return out
}

/** "orders/update.js" -> "orders/update"; "orders/index.js" -> "orders". */
export const routeOf = rel => rel.replace(/\.js$/, '').replace(/(^|\/)index$/, '')

export function tables() {
  const by = Object.fromEntries(GROUPS.map(g => [g, []]))
  for (const file of walk(ROUTES).sort()) {
    const rel = path.relative(ROUTES, file).split(path.sep).join('/')
    const route = routeOf(rel)
    const group = GROUP_OF[route.split('/')[0]] || 'app'
    by[group].push(`  '${route}': () => import('../../_routes/${rel}'),`)
  }
  return Object.fromEntries(GROUPS.map(g => [g,
    `// Generated by scripts/gen-routes.js (npm run routes). Do not edit by hand.\n` +
    `// The ${g} function (api/${g}.js): route under /api/ -> handler module.\n` +
    `export default {\n${by[g].join('\n')}\n}\n`]))
}

if (process.argv[1] === new URL(import.meta.url).pathname) {
  const check = process.argv.includes('--check')
  const want = tables()
  const stale = []
  for (const [g, text] of Object.entries(want)) {
    const file = path.join(OUT, `${g}.js`)
    const have = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null
    if (have === text) continue
    if (check) stale.push(`api/_lib/routes/${g}.js`)
    else { fs.mkdirSync(OUT, { recursive: true }); fs.writeFileSync(file, text) }
  }
  for (const f of fs.readdirSync(OUT)) {
    if (!want[f.replace(/\.js$/, '')]) { if (check) stale.push(`api/_lib/routes/${f} (no such group)`); else fs.unlinkSync(path.join(OUT, f)) }
  }
  // Every function file in api/ costs build memory: only the group entry
  // points may live there. A handler goes in api/_routes/ instead.
  const extra = walk(path.join(root, 'api'))
    .map(f => path.relative(path.join(root, 'api'), f).split(path.sep).join('/'))
    .filter(rel => !rel.split('/').some(part => part.startsWith('_') || part.startsWith('.')))
    .filter(rel => !GROUPS.includes(rel.replace(/\.js$/, '')))
    .map(rel => `api/${rel}`)
  if (check && (stale.length || extra.length)) {
    if (stale.length) console.error(`✖ Route tables out of date: ${stale.join(', ')}. Run \`npm run routes\`.`)
    if (extra.length) console.error(`✖ ${extra.join(', ')}: handlers go in api/_routes/ (each file in api/ is its own Vercel function). Move it and run \`npm run routes\`.`)
    process.exit(1)
  }
  const n = Object.values(want).reduce((s, t) => s + (t.match(/import\(/g) || []).length, 0)
  console.log(`routes ${check ? 'ok' : 'written'}: ${n} handlers in ${GROUPS.length} functions (${GROUPS.join(', ')})`)
}
